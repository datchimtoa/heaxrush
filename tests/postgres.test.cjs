// Opt in with TEST_DATABASE_URL for a disposable PostgreSQL database.
const test = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { Pool } = require('pg');
const { migrate } = require('../server/migrate.cjs');
const { createStore } = require('../server/store.cjs');
const { createGameStore } = require('../server/game-store.cjs');
const { createReplay } = require('../server/replay.cjs');
const { createCoinStore } = require('../server/coins.cjs');
const { createLeaderboardStore } = require('../server/leaderboards.cjs');
const { createAchievementStore } = require('../server/achievements.cjs');
const { createDailyStore, recordLoginDay } = require('../server/daily.cjs');

test('PostgreSQL migrations, auth lifecycle, authoritative scoring and append-only concurrent Coins ledger', { skip: !process.env.TEST_DATABASE_URL }, async () => {
	const schema = 'auth_test_' + randomUUID().replaceAll('-', '');
	const admin = new Pool({ connectionString: process.env.TEST_DATABASE_URL });
	await admin.query(`CREATE SCHEMA ${schema}`);
	const pool = new Pool({ connectionString: process.env.TEST_DATABASE_URL, options: `-c search_path=${schema}` });
	try {
		await migrate(pool);
		await migrate(pool);
		assert.equal((await pool.query('SELECT * FROM schema_migrations')).rowCount, 6);
		assert.equal((await pool.query('SELECT COUNT(*) AS count FROM login_streaks')).rows[0].count, '0', 'migration starts empty, never backfills visits');
		let loginTime = Date.now();
		const store = createStore(pool, () => loginTime);
		const input = { user: { telegramId: '12345', firstName: 'Test', lastName: '', username: null, languageCode: 'en' }, tokenHash: 'a'.repeat(64), launchHash: 'b'.repeat(64), expiresAt: new Date(Date.now() + 60000) };
		const user = await store.login(input);
		assert.equal((await pool.query('SELECT days FROM login_streaks WHERE user_id = $1', [user.id])).rows[0].days, 1);
		await Promise.all(Array.from({ length: 5 }, () => store.recordLaunch(user.id)));
		assert.equal((await pool.query('SELECT days FROM login_streaks WHERE user_id = $1', [user.id])).rows[0].days, 1);
		loginTime += 86400000;
		await Promise.all(Array.from({ length: 5 }, () => store.recordLaunch(user.id)));
		assert.equal((await pool.query('SELECT days FROM login_streaks WHERE user_id = $1', [user.id])).rows[0].days, 2);
		await recordLoginDay(pool, user.id, loginTime - 86400000);
		assert.equal((await pool.query('SELECT days FROM login_streaks WHERE user_id = $1', [user.id])).rows[0].days, 2, 'older in-flight request cannot roll streak back');
		loginTime += 2 * 86400000; await store.recordLaunch(user.id);
		assert.equal((await pool.query('SELECT days FROM login_streaks WHERE user_id = $1', [user.id])).rows[0].days, 1, 'missed day resets next launch');
		assert.equal((await pool.query('SELECT COUNT(*) AS count FROM coin_ledger')).rows[0].count, '0');
		assert.equal((await pool.query('SELECT COUNT(*) AS count FROM user_achievements')).rows[0].count, '0', 'validated streaks create no reward data');
		assert.equal((await store.getSession(input.tokenHash)).user.id, user.id);
		await assert.rejects(store.login({ ...input, tokenHash: 'c'.repeat(64) }), /already used/);
		assert.equal((await pool.query('SELECT days FROM login_streaks WHERE user_id = $1', [user.id])).rows[0].days, 1);
		const updated = await store.login({ ...input, user: { ...input.user, firstName: 'Changed', username: 'updated_player' }, tokenHash: 'c'.repeat(64), launchHash: 'd'.repeat(64) });
		assert.equal(updated.id, user.id);
		assert.equal(updated.firstName, 'Changed');
		assert.equal(updated.username, 'updated_player');
		assert.equal((await store.getSession('c'.repeat(64))).user.username, 'updated_player');
		let time = Date.now();
		const games = createGameStore(pool, () => time);
		const requestId = randomUUID();
		const game = await games.start(user.id, requestId);
		assert.equal((await games.start(user.id, requestId)).id, game.id);
		const replay = createReplay(game.seed);
		let ticks = 0;
		while (!replay.result().ended && ticks < 18000) { replay.advance(++ticks, []); }
		assert.equal(replay.result().ended, true);
		time += Math.ceil(ticks * 1000 / 60) + 1000;
		for (let fromTick = 0; fromTick < ticks;) {
			const toTick = Math.min(ticks, fromTick + 600);
			await games.events(user.id, game.id, { fromTick, toTick, events: [] });
			fromTick = toTick;
		}
		const [firstResult, retryResult] = await Promise.all([games.finish(user.id, game.id), games.finish(user.id, game.id)]);
		assert.deepEqual(firstResult, retryResult);
		assert.equal(firstResult.score, replay.result().score);
		const aggregates = (await pool.query('SELECT best_score, total_score, games_played FROM users WHERE id = $1', [user.id])).rows[0];
		assert.equal(aggregates.games_played, 1);
		assert.equal(Number(aggregates.total_score), firstResult.score);
		assert.equal(Number(aggregates.best_score), firstResult.score);
		const leaderboards = createLeaderboardStore(pool, () => time);
		const achievements = createAchievementStore(pool);
		const dailyProgress = createDailyStore(pool, () => time);
		assert.equal((await dailyProgress.progress(user.id)).quests[0].progress, 1);
		assert.equal((await achievements.progress(user.id)).rewardsEnabled, false);
		assert.equal((await achievements.progress(user.id)).milestones[0].progress, Math.min(500, firstResult.score));
		const daily = await leaderboards.standings(user.id, 'daily');
		assert.deepEqual(daily.own, { rank: 1, score: firstResult.score });
		assert.equal(daily.entries.length, 1); assert.equal(daily.entries[0].isYou, true);
		assert.equal(daily.entries[0].label, '@updated_player');
		assert.deepEqual(firstResult.coins, { awarded: 0, balance: 0, held: 0, issuanceEnabled: false, reversed: 0, flagged: false });
		const coins = createCoinStore(pool, () => time);
		assert.equal((await coins.summary(user.id)).entries.length, 0, 'official finish never auto-issues Coins');
		const operation = { type: 'earn', amount: 20, source: 'integration_fixture', referenceId: game.id, reason: 'Disposable database fixture only' };
		const [entry, duplicate] = await Promise.all([coins.change(user.id, operation), coins.change(user.id, operation)]);
		assert.deepEqual(entry, duplicate);
		assert.equal((await coins.summary(user.id)).balance, 20);
		assert.equal((await coins.summary(user.id)).entries.length, 1);
		await assert.rejects(coins.change(user.id, { ...operation, amount: 21 }), /Conflicting/);
		await assert.rejects(pool.query('UPDATE coin_ledger SET amount = 2 WHERE id = $1', [entry.id]), /append-only/);
		await assert.rejects(pool.query('DELETE FROM coin_ledger WHERE id = $1', [entry.id]), /append-only/);
		await assert.rejects(pool.query('TRUNCATE coin_ledger'), /append-only/);
		const debit = referenceId => coins.change(user.id, { ...operation, type: 'spend', amount: 15, referenceId });
		const debits = await Promise.allSettled([debit('spend-one'), debit('spend-two')]);
		assert.equal(debits.filter(result => result.status === 'fulfilled').length, 1, 'concurrent debits cannot overspend');
		assert.equal((await coins.summary(user.id)).balance, 5);
		await coins.change(user.id, { ...operation, type: 'hold', amount: 3, referenceId: 'hold' });
		await coins.change(user.id, { ...operation, type: 'release', amount: 2, referenceId: 'release' });
		await coins.change(user.id, { ...operation, type: 'reverse', amount: 1, referenceId: 'reverse' });
		assert.equal((await coins.summary(user.id)).held, 1);
		await assert.rejects(coins.change(user.id, { ...operation, type: 'release', amount: 2, referenceId: 'over-release' }), /Insufficient/);
		for (let i = 0; i < 22; i++) await coins.change(user.id, { ...operation, amount: 1, referenceId: 'page-' + i });
		const firstPage = await coins.summary(user.id);
		const nextPage = await coins.summary(user.id, firstPage.nextCursor);
		assert.equal(firstPage.entries.length, 20); assert.equal(nextPage.entries.length, 7);
		assert.equal(new Set([...firstPage.entries, ...nextPage.entries].map(item => item.id)).size, 27);
		const other = await store.login({ ...input, user: { ...input.user, telegramId: '67890' }, tokenHash: '1'.repeat(64), launchHash: '2'.repeat(64) });
		assert.deepEqual((await coins.summary(other.id, firstPage.nextCursor)).entries, [], 'foreign cursors disclose no history');
		assert.equal((await coins.summary(other.id)).balance, 0);
		assert.equal((await leaderboards.standings(other.id, 'weekly')).own, null, 'no game means no invented rank');
		assert.equal((await games.finish(user.id, game.id)).coins.awarded, 0, 'later retries never issue retroactive rewards');
		// Disposable database only: synthetic server-owned checkpoints isolate reward
		// accounting from play skill. Production clients cannot supply checkpoints.
		const rewardUser = await store.login({ ...input, user: { ...input.user, telegramId: '90123' }, tokenHash: '3'.repeat(64), launchHash: '4'.repeat(64) });
		const rewardGames = createGameStore(pool, () => time, true);
		const snapshot = replay.snapshot(); snapshot.score = 2000; snapshot.hex.bestCombo = 4;
		await coins.change(rewardUser.id, { ...operation, amount: 100, referenceId: 'other-source' });
		let creditedId, cappedId;
		for (let i = 0; i < 11; i++) {
			const run = await rewardGames.start(rewardUser.id, randomUUID());
			await pool.query('UPDATE game_sessions SET engine_state = $2::jsonb WHERE id = $1', [run.id, JSON.stringify(snapshot)]);
			const [first, duplicate] = await Promise.all([rewardGames.finish(rewardUser.id, run.id), rewardGames.finish(rewardUser.id, run.id)]);
			assert.deepEqual(first, duplicate); assert.equal(first.coins.awarded, i < 10 ? 10 : 0);
			if (i === 0) creditedId = run.id;
			if (i === 10) cappedId = run.id;
		}
		assert.equal((await coins.summary(rewardUser.id)).balance, 200);
		assert.deepEqual((await leaderboards.standings(rewardUser.id, 'daily')).own, { rank: 1, score: 2000 });
		assert.deepEqual((await leaderboards.standings(rewardUser.id, 'weekly')).own, { rank: 1, score: 22000 });
		assert.equal((await pool.query('SELECT * FROM user_achievements WHERE user_id = $1', [rewardUser.id])).rowCount, 4);
		assert.ok((await achievements.progress(rewardUser.id)).milestones.every(m => m.reached));
		assert.ok((await dailyProgress.progress(rewardUser.id)).quests.every(q => q.reached));
		assert.equal((await pool.query("SELECT * FROM coin_ledger WHERE user_id = $1 AND source = 'achievement'", [rewardUser.id])).rowCount, 0, 'no unapproved bonus payouts');
		await assert.rejects(coins.change(rewardUser.id, { ...operation, amount: 1, source: 'new_source', referenceId: 'over-cap' }), /Daily Coin cap/);
		const [flag, flagRetry] = await Promise.all([rewardGames.flag(rewardUser.id, creditedId, 'Fixture review'), rewardGames.flag(rewardUser.id, creditedId, 'Fixture review')]);
		assert.deepEqual(flag, { flagged: true, reversed: 10 }); assert.deepEqual(flag, flagRetry);
		assert.equal((await coins.summary(rewardUser.id)).balance, 190);
		assert.equal((await leaderboards.standings(rewardUser.id, 'weekly')).own.score, 20000, 'flagged sessions leave standings without rewriting user aggregates');
		assert.equal((await coins.summary(rewardUser.id)).daily.remainingGameplay, 0, 'reversals never reopen a gross earning cap');
		const flagged = await rewardGames.start(rewardUser.id, randomUUID());
		await rewardGames.flag(rewardUser.id, flagged.id, 'Pre-finish fixture review');
		await assert.rejects(rewardGames.finish(rewardUser.id, flagged.id), /flagged/);
		time += 86400000;
		assert.equal((await rewardGames.finish(rewardUser.id, cappedId)).coins.awarded, 0, 'next-day retries never backfill cap-blocked runs');
		await pool.query("UPDATE users SET status = 'blocked' WHERE id = $1", [rewardUser.id]);
		assert.equal((await leaderboards.standings(rewardUser.id, 'weekly')).own, null, 'blocked accounts never rank');
		assert.ok((await achievements.progress(rewardUser.id)).milestones.every(m => m.progress === 0), 'blocked accounts never contribute progress');
		assert.ok((await dailyProgress.progress(rewardUser.id)).quests.every(q => q.progress === 0));
		await assert.rejects(store.recordLaunch(rewardUser.id), /Account unavailable/);
		assert.deepEqual(await rewardGames.flag(rewardUser.id, creditedId, 'Blocked-account retry'), flag);
		await store.revoke(input.tokenHash);
		assert.equal(await store.getSession(input.tokenHash), null);
		await pool.query('UPDATE auth_sessions SET expires_at = NOW() - INTERVAL \'1 second\' WHERE token_hash = $1', ['c'.repeat(64)]);
		assert.equal(await store.getSession('c'.repeat(64)), null);
		await pool.query('UPDATE users SET status = \'blocked\' WHERE id = $1', [user.id]);
		await assert.rejects(coins.summary(user.id), /Account unavailable/);
		await assert.rejects(coins.change(user.id, { ...operation, referenceId: 'blocked' }), /Account unavailable/);
		await assert.rejects(store.login({ ...input, tokenHash: 'e'.repeat(64), launchHash: 'f'.repeat(64) }), /Account unavailable/);
	} finally {
		await pool.end();
		await admin.query(`DROP SCHEMA ${schema} CASCADE`);
		await admin.end();
	}
});